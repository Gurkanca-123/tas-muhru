def spin(s,a):
    # gövde çerçevesinde yazılmış pozu dikey eksende a derece döndürür (asa, ayak, dirsek/diz ipuçları dahil)
    s=dict(s); y,p,r=s['hipQ']; s['hipQ']=(y+a,p,r); s['hip']=rotv(s['hip'],a)
    for k in ('g','t','n','er','el','kl','kr','lfree'): s[k]=rotv(s[k],a)
    for k,yk in (('fl','fly'),('fr','fry')):
        R=FR[k]; ab=tuple(R[i]+s[k][i] for i in range(3)); ab=rotv(ab,a); s[k]=tuple(ab[i]-R[i] for i in range(3)); s[yk]=s[yk]+a
    return s
